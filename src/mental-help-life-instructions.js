/**
 * @param {string} title
 * @returns {string}
 */
export function getLifeQuestionInstruction(title) {
  const t = title.trim();
  if (!t || isLifeBlockTitle(t)) return "";
  if (LIFE_QUESTION_INSTRUCTIONS[t]) return LIFE_QUESTION_INSTRUCTIONS[t];
  for (const { test, instruction } of LIFE_QUESTION_INSTRUCTION_PATTERNS) {
    if (test.test(t)) return instruction;
  }
  if (/^Вопрос \d+\./.test(t) || /^Вопрос [АБВ]\d/.test(t)) {
    return "Выберите подходящий вариант или введите текст. Если не помните — используйте «не знаю» или «затрудняюсь ответить», где это предусмотрено.";
  }
  if (/^\d+\.\d+\./.test(t)) {
    return "Заполните поля по подсказкам. Если вопрос не относится к вашей ситуации — пропустите или выберите «не знаю».";
  }
  return "Ответьте по памяти; при сомнении выберите «не знаю», если такой вариант есть в форме.";
}

/**
 * @param {string} instruction
 * @param {string} title
 * @returns {string}
 */
function enrichHelpFromInstruction(instruction, title) {
  const extra =
    " Если нужны даты, частота или обстоятельства — укажите кратко в текстовом поле. Неуверенность — «не знаю» или «затрудняюсь ответить».";
  if (/^1\.\d+\./.test(title.trim())) {
    return `${instruction} Заполните только то, что относится к выбранному родственнику.${extra}`;
  }
  return `${instruction}${extra}`;
}

/**
 * @param {string} title
 * @returns {string}
 */
export function helpForLifeQuestion(title) {
  const t = title.trim();
  if (!t || isLifeBlockTitle(t)) return "";
  if (LIFE_QUESTION_HELP_EXTRA[t]) return LIFE_QUESTION_HELP_EXTRA[t];
  for (const { test, help } of LIFE_QUESTION_HELP_PATTERNS) {
    if (test.test(t)) return help;
  }
  const instruction = getLifeQuestionInstruction(title);
  if (instruction) return enrichHelpFromInstruction(instruction, title);
  return "Ответьте по памяти. Если не уверены — выберите «не знаю» или «затрудняюсь ответить», если в форме есть такой вариант.";
}
