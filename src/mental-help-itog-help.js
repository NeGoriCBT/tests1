const DISEASE_EPISODE_HELP =
  "Один период ухудшения состояния. Дебют — первый раз в жизни; повторное — после улучшения; текущее — длится сейчас. Заполняйте пункты 1–7 по порядку внутри эпизода.";

/**
 * @param {string} title
 */
export function helpForComplaintsBlock(title) {
  return (
    getComplaintBlockInstruction(title) ??
    "Отметьте один или несколько пунктов за последние 2 недели или опишите ситуацию в поле «Свой вариант»."
  );
}

/**
 * @param {string} title
 */
export function getDiseaseSectionInstruction(title) {
  const t = title.trim();
  if (DISEASE_LEGEND_INSTRUCTIONS[t]) return DISEASE_LEGEND_INSTRUCTIONS[t];
  if (/^Вопрос 4\./.test(t)) {
    return DISEASE_LEGEND_INSTRUCTIONS["Вопрос 4. Что происходило в жизни незадолго до начала или перед ухудшением?"];
  }
  if (/^\d+\./.test(t)) {
    return "Заполните по памяти; при сомнении отметьте «не помню», если такой вариант есть.";
  }
  return "";
}

/**
 * @param {string} title
 */
export function helpForDiseaseSection(title) {
  const t = title.trim();
  if (DISEASE_LEGEND_HELP[t]) return DISEASE_LEGEND_HELP[t];
  if (/^Эпизод \d+/.test(t)) return DISEASE_EPISODE_HELP;
  if (/^Вопрос 4\./.test(t)) {
    return DISEASE_LEGEND_HELP["Вопрос 4. Что происходило в жизни незадолго до начала или перед ухудшением?"];
  }
  if (/^\d+\./.test(t)) {
    const instr = getDiseaseSectionInstruction(title);
    return instr
      ? `${instr} Подробности (даты, примеры) помогут точнее описать эпизод в итоговом тексте.`
      : "Опишите этот пункт по памяти; при сомнении используйте «не помню».";
  }
  return "Эти сведения войдут в раздел «Анамнез заболевания» в итоговом документе.";
}
