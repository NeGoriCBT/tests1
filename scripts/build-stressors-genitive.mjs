const catalogPath = path.join(ROOT, "src/mental-help-disease-stressors-catalog.js");
const { STRESSORS_CATALOG } = await import(pathToFileURL(catalogPath));

/** @type {string[]} */
const missing = [];
/** @type {string[]} */
const allLabels = [];

for (const g of STRESSORS_CATALOG) {
  for (const lab of g.items) {
    if (allLabels.includes(lab)) continue;
    allLabels.push(lab);
    if (!(lab in GENITIVE)) missing.push(lab);
  }
}

if (missing.length) {
  console.error("Missing genitive for catalog labels:");
  for (const m of missing) console.error(`  - ${m}`);
  process.exit(1);
}

const extra = Object.keys(GENITIVE).filter((k) => !allLabels.includes(k));
if (extra.length) {
  console.warn("Genitive map has keys not in catalog:", extra.join(", "));
}

const body =
  `/**\n * Автогенерация: node scripts/build-stressors-genitive.mjs\n` +
  ` * Родительный падеж стрессоров для «на фоне …».\n` +
  ` * Пунктов: ${allLabels.length}\n */\n` +
  `/** @type {Readonly<Record<string, string>>} */\n` +
  `export const STRESSOR_GENITIVE_BY_LABEL = ${JSON.stringify(GENITIVE, null, 2)};\n`;

fs.writeFileSync(OUT, body, "utf8");
console.log(`Wrote ${OUT}: ${allLabels.length} entries`);

/**
 * @param {string} p
 */
function pathToFileURL(p) {
  return new URL(`file://${p}`).href;
}
